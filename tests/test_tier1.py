    def test_f5_tex_table_inclusion(self):
        """REQ-10: Verify table formatting complies with LaTeX booktabs standard (no vertical rules)."""
        self.assertTrue(self.tex_file.exists(), f"Artifact {self.tex_file} does not exist.")
        content = self.tex_file.read_text(encoding="utf-8")

        # Must include booktabs package in preamble
        self.assertIn("\\usepackage{booktabs}", content, "manuscript.tex missing \\usepackage{booktabs}")

        # Check for booktabs rules
        self.assertIn("\\toprule", content, "manuscript.tex tables must use \\toprule")
        self.assertIn("\\midrule", content, "manuscript.tex tables must use \\midrule")
        self.assertIn("\\bottomrule", content, "manuscript.tex tables must use \\bottomrule")

        # Must not contain vertical table rules (|) in tabular column declarations
        # e.g., \begin{tabular}{|c|c|} is forbidden by publication standards
        tabular_specs = re.findall(r"\\begin\{tabular\*?\}(?:\{[^}]*\})?\{([^}]+)\}", content)
        for spec in tabular_specs:
            self.assertNotIn(
                "|",
                spec,
                f"Publication table uses forbidden vertical bar '|' in column specification: '{spec}'",
            )

